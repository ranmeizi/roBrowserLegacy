/**
 * Build an frpc visitor package (zip).
 *
 * - GitHub Actions (windows-latest): Windows amd64 zip with frpc.exe
 * - macOS / Linux local: native frpc binary for the current machine
 *
 * Package contents:
 *   frpc(.exe), frpc.toml, start script, README.txt
 *
 * frpc.toml intentionally OMITS the SSH visitor (aidlux_ssh / bindPort 2822).
 * Only: ro-robrowser (8010), ro-wsproxy (5999), ro-remote-client (3338).
 *
 * Required env:
 *   FRP_AUTH_TOKEN, FRP_SECRET_KEY
 *
 * Optional env:
 *   FRP_VERSION (default 0.61.1)
 *   FRP_SERVER_ADDR (default 120.26.102.118)
 *   FRP_SERVER_PORT (default 7000)
 *   FRP_TARGET=windows|darwin|linux  (default: current platform)
 *   FRP_ARCH=amd64|arm64            (default: current arch; windows always amd64)
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { execFileSync } from 'child_process';
import https from 'https';
import http from 'http';
import { createWriteStream } from 'fs';
import { pipeline } from 'stream/promises';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '../..');
const CACHE_DIR = path.join(ROOT, 'dist', '.cache');

const FRP_VERSION = process.env.FRP_VERSION || '0.61.1';
const SERVER_ADDR = process.env.FRP_SERVER_ADDR || '120.26.102.118';
const SERVER_PORT = Number(process.env.FRP_SERVER_PORT || 7000);
const AUTH_TOKEN = process.env.FRP_AUTH_TOKEN || '';
const SECRET_KEY = process.env.FRP_SECRET_KEY || '';

function detectTarget() {
	const forced = (process.env.FRP_TARGET || '').toLowerCase();
	if (forced === 'windows' || forced === 'darwin' || forced === 'linux') {
		return forced;
	}
	if (process.platform === 'win32') {
		return 'windows';
	}
	if (process.platform === 'darwin') {
		return 'darwin';
	}
	return 'linux';
}

function detectArch(target) {
	const forced = (process.env.FRP_ARCH || '').toLowerCase();
	if (forced === 'amd64' || forced === 'arm64') {
		return forced;
	}
	// Official Windows release commonly used as amd64
	if (target === 'windows') {
		return 'amd64';
	}
	return process.arch === 'arm64' ? 'arm64' : 'amd64';
}

const TARGET = detectTarget();
const ARCH = detectArch(TARGET);
const OS_NAME = TARGET === 'windows' ? 'windows' : TARGET === 'darwin' ? 'darwin' : 'linux';
const ARCHIVE_BASE = `frp_${FRP_VERSION}_${OS_NAME}_${ARCH}`;
const ARCHIVE_NAME = `${ARCHIVE_BASE}.zip`;
const DOWNLOAD_URL = `https://github.com/fatedier/frp/releases/download/v${FRP_VERSION}/${ARCHIVE_NAME}`;
const OUT_DIR = path.join(ROOT, 'dist', `frpc-visitor-${TARGET}`);
const BIN_NAME = TARGET === 'windows' ? 'frpc.exe' : 'frpc';

function ensureDir(dir) {
	fs.mkdirSync(dir, { recursive: true });
}

function rmrf(dir) {
	if (fs.existsSync(dir)) {
		fs.rmSync(dir, { recursive: true, force: true });
	}
}

function download(url, dest) {
	return new Promise((resolve, reject) => {
		const file = createWriteStream(dest);
		const get = url.startsWith('https') ? https.get : http.get;

		const request = get(url, res => {
			if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
				file.close();
				if (fs.existsSync(dest)) {
					fs.unlinkSync(dest);
				}
				download(res.headers.location, dest).then(resolve).catch(reject);
				return;
			}
			if (res.statusCode !== 200) {
				file.close();
				reject(new Error(`Download failed: HTTP ${res.statusCode} for ${url}`));
				return;
			}
			pipeline(res, file).then(resolve).catch(reject);
		});

		request.on('error', err => {
			file.close();
			reject(err);
		});
	});
}

function unzip(zipPath, destDir) {
	ensureDir(destDir);
	if (process.platform === 'win32') {
		execFileSync(
			'powershell.exe',
			['-NoProfile', '-Command', `Expand-Archive -Force -Path '${zipPath}' -DestinationPath '${destDir}'`],
			{ stdio: 'inherit' }
		);
	} else {
		execFileSync('unzip', ['-o', zipPath, '-d', destDir], { stdio: 'inherit' });
	}
}

function findFrpcBinary(extractRoot) {
	const wanted = TARGET === 'windows' ? 'frpc.exe' : 'frpc';
	const stack = [extractRoot];
	while (stack.length) {
		const dir = stack.pop();
		for (const name of fs.readdirSync(dir)) {
			const full = path.join(dir, name);
			const st = fs.statSync(full);
			if (st.isDirectory()) {
				stack.push(full);
			} else if (name === wanted) {
				return full;
			}
		}
	}
	return null;
}

function writeToml(filePath) {
	// SSH visitor (aidlux_ssh / bindPort 2822) must NEVER be included.
	const toml = `# Generated by build-frpc-visitor.mjs — visitors only (no SSH).

serverAddr = "${SERVER_ADDR}"
serverPort = ${SERVER_PORT}
auth.token = "${AUTH_TOKEN}"

[[visitors]]
name = "ro-robrowser"
type = "stcp"
serverName = "robrowser"
secretKey = "${SECRET_KEY}"
bindPort = 8010

[[visitors]]
name = "ro-wsproxy"
type = "stcp"
serverName = "wsproxy"
secretKey = "${SECRET_KEY}"
bindPort = 5999

[[visitors]]
name = "ro-remote-client"
type = "stcp"
serverName = "remote-client"
secretKey = "${SECRET_KEY}"
bindPort = 3338
`;
	fs.writeFileSync(filePath, toml, 'utf8');
}

function writeRedirectHtml(filePath) {
	const html = `<!DOCTYPE html>
<html lang="zh-CN">
<head>
	<meta charset="UTF-8" />
	<meta http-equiv="refresh" content="0;url=http://127.0.0.1:8010/" />
	<title>打开 roBrowser</title>
	<script>
		location.replace('http://127.0.0.1:8010/');
	</script>
</head>
<body>
	<p>正在打开游戏…若未跳转请点击：
		<a href="http://127.0.0.1:8010/">http://127.0.0.1:8010/</a>
	</p>
</body>
</html>
`;
	fs.writeFileSync(filePath, html, 'utf8');
}

function writeStartScript(dir) {
	if (TARGET === 'windows') {
		fs.writeFileSync(
			path.join(dir, 'start.bat'),
			`@echo off
cd /d "%~dp0"
echo Starting frpc visitor (robrowser:8010, wsproxy:5999, remote-client:3338)...
echo SSH visitor is NOT included.
start "" "open-game.html"
frpc.exe -c frpc.toml
pause
`,
			'utf8'
		);
		return;
	}

	const sh = `#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
echo "Starting frpc visitor (robrowser:8010, wsproxy:5999, remote-client:3338)..."
echo "SSH visitor is NOT included."
if command -v open >/dev/null 2>&1; then
  open ./open-game.html
elif command -v xdg-open >/dev/null 2>&1; then
  xdg-open ./open-game.html >/dev/null 2>&1 || true
fi
exec ./frpc -c frpc.toml
`;
	const shPath = path.join(dir, 'start.sh');
	fs.writeFileSync(shPath, sh, 'utf8');
	fs.chmodSync(shPath, 0o755);
}

function writeReadme(filePath) {
	const startHint = TARGET === 'windows' ? 'Double-click start.bat' : './start.sh   (or: ./frpc -c frpc.toml)';
	const text = `roBrowser frpc visitor (${TARGET}/${ARCH})
==========================================

1. ${startHint}
2. Keep the process running
3. Browser opens via open-game.html -> http://127.0.0.1:8010/
   (or open open-game.html manually)

Ports:
  8010 -> robrowser
  5999 -> wsproxy
  3338 -> remote-client

SSH is intentionally NOT packaged.
`;
	fs.writeFileSync(filePath, text, 'utf8');
}

function zipFolder(folderPath, zipPath) {
	if (fs.existsSync(zipPath)) {
		fs.unlinkSync(zipPath);
	}
	const parent = path.dirname(folderPath);
	const base = path.basename(folderPath);
	if (process.platform === 'win32') {
		execFileSync(
			'powershell.exe',
			[
				'-NoProfile',
				'-Command',
				`Compress-Archive -Force -Path (Join-Path '${folderPath}' '*') -DestinationPath '${zipPath}'`
			],
			{ stdio: 'inherit' }
		);
	} else {
		execFileSync('zip', ['-r', zipPath, base], { cwd: parent, stdio: 'inherit' });
	}
}

async function main() {
	if (!AUTH_TOKEN || !SECRET_KEY) {
		throw new Error('FRP_AUTH_TOKEN and FRP_SECRET_KEY env vars are required');
	}

	console.log(`[frpc-visitor] host=${process.platform}/${process.arch} target=${TARGET}/${ARCH}`);
	console.log(`[frpc-visitor] version=${FRP_VERSION} server=${SERVER_ADDR}:${SERVER_PORT}`);
	console.log('[frpc-visitor] visitors: ro-robrowser, ro-wsproxy, ro-remote-client (NO ssh)');

	ensureDir(CACHE_DIR);
	rmrf(OUT_DIR);
	ensureDir(OUT_DIR);

	const zipDownload = path.join(CACHE_DIR, ARCHIVE_NAME);
	if (!fs.existsSync(zipDownload)) {
		console.log(`[frpc-visitor] downloading ${DOWNLOAD_URL}`);
		await download(DOWNLOAD_URL, zipDownload);
	} else {
		console.log(`[frpc-visitor] using cached ${zipDownload}`);
	}

	const extractDir = path.join(CACHE_DIR, ARCHIVE_BASE);
	rmrf(extractDir);
	unzip(zipDownload, extractDir);

	const frpcBin = findFrpcBinary(extractDir);
	if (!frpcBin) {
		throw new Error(`${BIN_NAME} not found in downloaded archive`);
	}

	const destBin = path.join(OUT_DIR, BIN_NAME);
	fs.copyFileSync(frpcBin, destBin);
	if (TARGET !== 'windows') {
		fs.chmodSync(destBin, 0o755);
	}

	writeToml(path.join(OUT_DIR, 'frpc.toml'));
	writeRedirectHtml(path.join(OUT_DIR, 'open-game.html'));
	writeStartScript(OUT_DIR);
	writeReadme(path.join(OUT_DIR, 'README.txt'));

	const tomlText = fs.readFileSync(path.join(OUT_DIR, 'frpc.toml'), 'utf8');
	if (/aidlux_ssh|bindPort\s*=\s*2822|\bname\s*=\s*"ssh"/i.test(tomlText)) {
		throw new Error('Refusing to package: SSH visitor leaked into frpc.toml');
	}

	const outZip = path.join(ROOT, 'dist', `frpc-visitor-${TARGET}-${ARCH}-v${FRP_VERSION}.zip`);
	zipFolder(OUT_DIR, outZip);

	console.log(`[frpc-visitor] package folder: ${OUT_DIR}`);
	console.log(`[frpc-visitor] zip: ${outZip}`);
}

main().catch(err => {
	console.error('[frpc-visitor] failed:', err.message);
	process.exit(1);
});
